"""Compare an edge-case run against the expectations and write a Markdown report.

Usage: python scripts/edge_report.py [--fixtures tests/fixtures/edge] [--outbox results/edge_outbox.json]
                                     [--report results/EDGE_CASES.md]

Evaluation only: the agent never reads _cases.json / _expected.json (a test enforces this).
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def load(path: Path, default):
    try:
        return json.loads(Path(path).read_text(encoding="utf-8"))
    except Exception:
        return default


def check(entry: dict | None, exp: dict) -> list[str]:
    """Return the list of failed expectations ([] = PASS)."""
    if entry is None:
        return ["no outbox entry"]
    fails = []
    refs = set(entry.get("policy_refs", []))
    reply = entry.get("reply_draft", "")
    if "category" in exp and entry["category"] not in exp["category"]:
        fails.append(f"category {entry['category']} not in {exp['category']}")
    if "escalate" in exp and entry["escalate"] != exp["escalate"]:
        fails.append(f"escalate {entry['escalate']} != {exp['escalate']}")
    if "priority" in exp and entry["priority"] not in exp["priority"]:
        fails.append(f"priority {entry['priority']} not in {exp['priority']}")
    missing = [r for r in exp.get("required_refs", []) if r not in refs]
    if missing:
        fails.append(f"missing refs {missing}")
    bad = [r for r in exp.get("forbidden_refs", []) if r in refs]
    if bad:
        fails.append(f"forbidden refs {bad}")
    if "max_refs" in exp and len(refs) > exp["max_refs"]:
        fails.append(f"{len(refs)} refs > {exp['max_refs']}")
    for s in exp.get("must_not_contain", []):
        if s.lower() in reply.lower():
            fails.append(f"reply contains '{s}'")
    if exp.get("reply_contains_any") and not any(s.lower() in reply.lower() for s in exp["reply_contains_any"]):
        fails.append(f"reply lacks any of {exp['reply_contains_any']}")
    if "reply_starts" in exp and not reply.startswith(exp["reply_starts"]):
        fails.append(f"reply does not start with '{exp['reply_starts']}'")
    for s in exp.get("notes_contain", []):
        if s.lower() not in entry.get("agent_notes", "").lower():
            fails.append(f"notes lack '{s}'")
    if "max_confidence" in exp and entry["confidence"] > exp["max_confidence"]:
        fails.append(f"confidence {entry['confidence']} > {exp['max_confidence']}")
    return fails


def evaluate(fixtures: Path, outbox_path: Path, trace_path: Path | None = None) -> list[dict]:
    """One row per fixture: case, expectation, actual decision, PASS/CHECK."""
    cases = load(fixtures / "_cases.json", {})
    expected = load(fixtures / "_expected.json", {})
    outbox = {e["email_id"]: e for e in load(outbox_path, []) if isinstance(e, dict)}
    trace_path = trace_path or outbox_path.with_name(outbox_path.stem.replace("outbox", "trace") + ".json")
    traces = load(trace_path, {}).get("emails", {})
    by_file = {t.get("file"): eid for eid, t in traces.items()}
    rows = []
    for file in sorted(set(cases) | set(expected)):
        eid = by_file.get(file) or Path(file).stem
        entry = outbox.get(eid)
        fails = check(entry, expected.get(file, {}))
        t = traces.get(eid, {})
        rows.append({
            "file": file, "email_id": eid, "case": cases.get(file, {}).get("case", ""),
            "expected": cases.get(file, {}).get("expected", ""),
            "category": entry["category"] if entry else "-", "priority": entry["priority"] if entry else "-",
            "escalate": entry["escalate"] if entry else None,
            "policy_refs": entry["policy_refs"] if entry else [],
            "confidence": entry["confidence"] if entry else None,
            "reply": (entry or {}).get("reply_draft", ""), "agent_notes": (entry or {}).get("agent_notes", ""),
            "escalation_reason": (entry or {}).get("escalation_reason", ""),
            "source": "fallback" if t.get("fallback") else ("invalid" if t.get("invalid") else (t.get("model") or "-")),
            "status": "PASS" if not fails else "CHECK", "fails": fails,
        })
    return rows


def excerpt(text: str, n: int = 90) -> str:
    body = " ".join(line for line in text.splitlines()[1:] if line.strip() and "Student Helpdesk" not in line
                    and not line.startswith("Regards"))
    body = body.replace("|", "/")
    return (body[:n] + "…") if len(body) > n else body


def to_markdown(rows: list[dict]) -> str:
    passed = sum(r["status"] == "PASS" for r in rows)
    lines = [
        "# Edge case results",
        "",
        "Generated by `python scripts/edge_report.py` from `results/edge_outbox.json`. Each row is one file in",
        "`tests/fixtures/edge/`; *case* and *expected* come from `_cases.json`, the checks from `_expected.json`",
        "(evaluation data only; the agent never reads them).",
        "",
        f"**{passed} / {len(rows)} PASS**" + (f", {len(rows) - passed} CHECK" if passed < len(rows) else ""),
        "",
        "| # | file | what it tests | expected | category | prio | esc | refs | conf | source | reply excerpt | result |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for i, r in enumerate(rows, 1):
        result = "✅ PASS" if r["status"] == "PASS" else "⚠️ CHECK: " + "; ".join(r["fails"])
        lines.append(
            f"| {i} | `{r['file']}` | {r['case']} | {r['expected']} | {r['category']} | {r['priority']} | "
            f"{'yes' if r['escalate'] else 'no'} | {', '.join(r['policy_refs']) or '-'} | "
            f"{r['confidence'] if r['confidence'] is not None else '-'} | {r['source']} | {excerpt(r['reply'])} | {result} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--fixtures", default="tests/fixtures/edge", type=Path)
    ap.add_argument("--outbox", default="results/edge_outbox.json", type=Path)
    ap.add_argument("--report", default="results/EDGE_CASES.md", type=Path)
    args = ap.parse_args()
    rows = evaluate(args.fixtures, args.outbox)
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(to_markdown(rows), encoding="utf-8")
    passed = sum(r["status"] == "PASS" for r in rows)
    print(f"{passed}/{len(rows)} PASS -> {args.report}")
    for r in rows:
        if r["status"] != "PASS":
            print(f"  CHECK {r['file']}: {'; '.join(r['fails'])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
